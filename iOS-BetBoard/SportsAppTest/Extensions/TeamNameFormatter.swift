    /// Formats a team name from Firebase format (lowercase) to display format
    /// Example: "charleston-southern" -> "Charleston Southern"
    /// - Parameter firebaseName: The team name in Firebase format (lowercase, possibly hyphenated)
    /// - Returns: The formatted team name for display
    static func formatTeamName(_ firebaseName: String) -> String {
        return teamMapping[firebaseName.uppercased()] ?? formatUnknownTeam(firebaseName)
    }
    
    /// Formats an unknown team name by converting hyphens to spaces and capitalizing words
    /// - Parameter name: The team name to format
    /// - Returns: The formatted team name
    private static func formatUnknownTeam(_ name: String) -> String {
        let formattedName = name.replacingOccurrences(of: "-", with: " ")
        return formattedName
            .split(separator: " ")
            .map { $0.prefix(1).uppercased() + $0.dropFirst().lowercased() }
            .joined(separator: " ")
    }
    
