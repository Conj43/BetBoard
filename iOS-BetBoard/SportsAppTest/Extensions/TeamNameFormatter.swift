// MARK: - Extensions
extension String {
    /// Converts a display format team name to Firebase format (uppercase with hyphens)
    /// Example: "North Carolina" -> "NORTH-CAROLINA"
    var toFirebaseFormat: String {
        // First check if we have a reverse mapping
        for (key, value) in TeamNameFormatter.teamMapping {
            if value == self {
                return key
            }
        }
        
        // Otherwise format based on conventions
        return self.uppercased().replacingOccurrences(of: " ", with: "-")
    }
}
